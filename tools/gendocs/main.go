// Command gendocs writes docs/reference from the product itself (E3-1).
//
// Nothing here is a second opinion about what KelyfOS does. The command list and
// every flag come from running the CLI's own `-h`, so what the reference prints
// is what a user is shown. The MCP tools come from running the supervisor's
// --dump-tools, so they are the guest's own `tools/list` answer. The toml keys,
// the event types and the exit codes come from tables the product depends on:
// config.Schema() builds the parser's unknown-key errors, recorder.Types()
// carries the fields the writer sets, exitcode is what the CLI returns.
//
// It also verifies before it writes, because generation alone is not enough. A
// command that exists and is missing from the usage block would be silently
// absent from the reference, so the dispatch switch in host/main.go is read and
// compared. The equivalent checks for keys and event types live as tests beside
// the tables they check.
//
// `make docs` runs this; CI runs `make docs` and fails on any diff (F-D4).
package main

