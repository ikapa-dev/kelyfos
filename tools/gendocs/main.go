// profilesPage is the guest confinement every flavor applies, asked of the
// supervisor rather than transcribed from it (P5-3).
//
// The page is deliberately architecture-independent: it prints syscall names and
// never their numbers. A refusal list is numbers by the time the kernel sees it
// and the same name is a different number on another architecture, so a page
// built from numbers would fail its own drift check depending on which machine
// ran `make docs`. `kelyfos-supervisor --dump-profile` prints the resolved
// numbers for the machine it runs on, and the acceptance reads them there.
// backticked joins paths as an inline code list, in the order the profile named
// them: the order is the order the rules are applied in, not alphabetical.
func backticked(paths []string) string {
	q := make([]string, len(paths))
	for i, p := range paths {
		q[i] = "`" + p + "`"
	}
	return strings.Join(q, ", ")
}

func profilesPage(sup string) (string, error) {
	out, err := exec.Command(sup, "--dump-profile", "base", "dev").Output()
	if err != nil {
		return "", fmt.Errorf("supervisor --dump-profile: %w", err)
	}

	type profile struct {
		name        string
		arch        string
		abi         string
		write       []string
		writeTree   []string
		writeDevice []string
		refused     []string
	}
	var profiles []profile
	var cur *profile
	for _, line := range strings.Split(string(out), "\n") {
		f := strings.Fields(line)
		if len(f) == 0 {
			continue
		}
		switch f[0] {
		case "flavor":
			profiles = append(profiles, profile{name: f[1]})
			cur = &profiles[len(profiles)-1]
		case "arch":
			cur.arch = f[1]
		case "landlock-abi-min":
			cur.abi = f[1]
		case "write":
			cur.write = append(cur.write, f[1])
		case "write-tree":
			cur.writeTree = append(cur.writeTree, f[1])
		case "write-device":
			cur.writeDevice = append(cur.writeDevice, f[1])
		case "refuse":
			// The name only. A syscall's number is the architecture's, and
			// `make docs` runs on whichever architecture CI uses, so a page
			// built from numbers would fail its own diff check on the other
			// one. The numbers are in `supervisor --dump-profile`, which the
			// acceptance reads.
			cur.refused = append(cur.refused, "`"+f[1]+"`")
		}
	}
	if len(profiles) == 0 {
		return "", fmt.Errorf("supervisor --dump-profile described no flavors")
	}

	var b strings.Builder
	b.WriteString(banner)
	b.WriteString("# Guest confinement profiles\n\n")
	b.WriteString("What the supervisor grants every process it spawns \u2014 `exec`, a plugin, and the\n" +
		"interactive shell alike. It is applied by a re-exec of the supervisor that restricts\n" +
		"itself and then runs the real program, so the restrictions belong to the child and\n" +
		"never to the supervisor. [`../hardening.md`](../hardening.md) \u00a74 says why each\n" +
		"mechanism is here and what it does not do.\n\n")
	b.WriteString("**Landlock** governs the filesystem: the listed trees are writable, everything\n" +
		"else on the image is readable and executable, and nothing else is writable. The\n" +
		"device trees are writable the same way the others are \u2014 a program may create files\n" +
		"and directories under them \u2014 which for `/dev/shm` means a general-purpose writable\n" +
		"area the guest kernel sizes at half the machine's RAM. The named device nodes are\n" +
		"narrower: read, write and truncate that file, and nothing else.\n" +
		"**seccomp** refuses the listed syscalls with `EPERM` \u2014 a refusal list rather than\n" +
		"an allowlist, because an allowlist for an arbitrary agent command is a crash waiting\n" +
		"to be mistaken for a security feature.\n\n")
	b.WriteString("The policy is the same on every architecture KelyfOS builds for. A name that is\n" +
		"not a syscall on some architecture \u2014 `settimeofday` has none on aarch64, which has\n" +
		"only `clock_settime` \u2014 is absent from that build's filter rather than faked, and\n" +
		"`kelyfos-supervisor --dump-profile` prints the resolved numbers for the machine it\n" +
		"runs on.\n")

	for _, p := range profiles {
		fmt.Fprintf(&b, "\n## `%s`\n\n", p.name)
		fmt.Fprintf(&b, "Refuses to run where the Landlock ABI is below **%s**.\n\n", p.abi)
		b.WriteString("Writable: " + backticked(p.write) + "\n\n")
		if len(p.writeTree) > 0 {
			b.WriteString("Writable device trees: " + backticked(p.writeTree) + "\n\n")
		}
		if len(p.writeDevice) > 0 {
			b.WriteString("Writable device nodes, read/write/truncate only: " +
				backticked(p.writeDevice) + "\n\n")
		}
		fmt.Fprintf(&b, "Refused, %d syscalls: %s\n", len(p.refused), strings.Join(p.refused, ", "))
	}
	b.WriteString("\n## Attaching a debugger\n\n")
	b.WriteString("Every process the supervisor spawns gets its **own** Landlock domain, and Landlock\n" +
		"refuses `ptrace` between sibling domains \u2014 which two commands in the same sandbox are.\n" +
		"So attaching to a process that is already running fails with `Operation not permitted`\n" +
		"on every flavor, including `dev`, whose profile leaves `ptrace` out of its refusal list\n" +
		"on purpose. One command also cannot read another's `/proc/<pid>/exe`.\n\n")
	b.WriteString("**Launching a program under a debugger works**, on `dev`: a child inherits its\n" +
		"parent's domain, so it is not a sibling. That is the whole of what `dev` buys here and\n" +
		"what `base` refuses. Neither image ships a debugger, so this is about what you install\n" +
		"into a `dev` sandbox. Why it is not a per-flavor knob is D33 in `docs/decisions.md`.\n")
	return b.String(), nil
}

// hostTools asks `kelyfos serve-mcp` for its own tools/list, over the protocol,
// the way a client would. Driving the server rather than reading a table means
// the page cannot describe a surface the server does not actually advertise —
// which is the same reason the guest's half comes from --dump-tools (E4-1).
func hostTools(bin string) ([]mcp.Tool, error) {
	cmd := exec.Command(bin, "serve-mcp")
	cmd.Stdin = strings.NewReader(strings.Join([]string{
		`{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-11-25","capabilities":{},"clientInfo":{"name":"gendocs","version":"1"}}}`,
		`{"jsonrpc":"2.0","method":"notifications/initialized"}`,
		`{"jsonrpc":"2.0","id":2,"method":"tools/list"}`,
		"",
	}, "\n"))
	var buf strings.Builder
	cmd.Stdout = &buf
	if err := cmd.Run(); err != nil {
		if _, ok := err.(*exec.ExitError); !ok {
			return nil, err
		}
	}
	for _, line := range strings.Split(buf.String(), "\n") {
		if !strings.Contains(line, `"tools"`) {
			continue
		}
		var resp struct {
			Result struct {
				Tools []mcp.Tool `json:"tools"`
			} `json:"result"`
		}
		if err := json.Unmarshal([]byte(line), &resp); err == nil && len(resp.Result.Tools) > 0 {
			return resp.Result.Tools, nil
		}
	}
	return nil, fmt.Errorf("serve-mcp did not answer tools/list")
}

func toolsPage(sup, bin string) (string, error) {
	text, err := capture(sup, "--dump-tools")
	if err != nil {
		return "", fmt.Errorf("asking the supervisor for its tools: %w", err)
	}
	var d toolDump
	if err := json.Unmarshal([]byte(text), &d); err != nil {
		return "", fmt.Errorf("reading the supervisor's tool list: %w", err)
	}

	var b strings.Builder
	b.WriteString(banner)
	b.WriteString("\n# MCP tools\n\n" +
		"What an agent attached to a sandbox can call, exactly as the guest advertises\n" +
		"it in `tools/list`. Attach with `kelyfos mcp`.\n\n" +
		"Which tools appear depends on what the sandbox is: the team tools exist only\n" +
		"for a sandbox in a team, and `team_spawn` only for an agent whose policy\n" +
		"granted a spawn budget. A tool that is always advertised and always fails\n" +
		"teaches a model to ignore failures, so it is not advertised (F-D18).\n\n" +
		"A `[[plugin]]` in `kelyfos.toml` adds its own tools on top of these, namespaced\n" +
		"under the plugin's name. They come from that server rather than from KelyfOS,\n" +
		"so they are not listed here — `tools/list` on a running sandbox is the only\n" +
		"complete answer for a machine that has one.\n")

	host, err := hostTools(bin)
	if err != nil {
		return "", fmt.Errorf("asking serve-mcp for its tools: %w", err)
	}

	groups := []struct {
		title string
		doc   string
		tools []mcp.Tool
	}{
		{"Every sandbox", "Always available.", d.Base},
		{"In a team", "Added when this sandbox is a member of a team.", d.Team},
		{"With a spawn budget", "Added when the team policy granted this agent one.", d.TeamSpawn},
	}
	for _, g := range groups {
		fmt.Fprintf(&b, "\n## %s\n\n%s\n", g.title, g.doc)
		for _, t := range g.tools {
			fmt.Fprintf(&b, "\n### `%s`\n\n%s\n\n", t.Name, t.Description)
			if len(t.InputSchema.Properties) == 0 {
				b.WriteString("No parameters.\n")
				continue
			}
			required := map[string]bool{}
			for _, r := range t.InputSchema.Required {
				required[r] = true
			}
			names := make([]string, 0, len(t.InputSchema.Properties))
			for n := range t.InputSchema.Properties {
				names = append(names, n)
			}
			sort.Strings(names)
			b.WriteString("| Parameter | Type | Required | Meaning |\n| --- | --- | --- | --- |\n")
			for _, n := range names {
				p := t.InputSchema.Properties[n]
				typ := p.Type
				if p.Items != nil {
					typ += " of " + p.Items.Type
				}
				req := "no"
				if required[n] {
					req = "**yes**"
				}
				fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", n, typ, req, cell(p.Description))
			}
		}
	}
	// The other direction: what a client attached to `kelyfos serve-mcp` sees.
	// Two surfaces in one page because a reader asking "what tools are there"
	// means both, and the difference between them is which side of the wall the
	// caller is on.
	b.WriteString("\n---\n\n## Driving KelyfOS from outside: `kelyfos serve-mcp`\n\n" +
		"These are the host's tools, not a guest's. An MCP client that runs\n" +
		"`kelyfos serve-mcp` gets them, and can boot sandboxes rather than work inside\n" +
		"one. Everything they do is bounded by the project's `kelyfos.toml`, and none of\n" +
		"them can widen it (`docs/mcp-surface.md`).\n")
	writeTools(&b, host)

	return b.String(), nil
}

// writeTools renders one group of tools with their parameters.
func writeTools(b *strings.Builder, tools []mcp.Tool) {
	for _, t := range tools {
		fmt.Fprintf(b, "\n### `%s`\n\n%s\n\n", t.Name, t.Description)
		if len(t.InputSchema.Properties) == 0 {
			b.WriteString("No parameters.\n")
			continue
		}
		required := map[string]bool{}
		for _, r := range t.InputSchema.Required {
			required[r] = true
		}
		names := make([]string, 0, len(t.InputSchema.Properties))
		for n := range t.InputSchema.Properties {
			names = append(names, n)
		}
		sort.Strings(names)
		b.WriteString("| Parameter | Type | Required | Meaning |\n| --- | --- | --- | --- |\n")
		for _, n := range names {
			p := t.InputSchema.Properties[n]
			typ := p.Type
			if p.Items != nil {
				typ += " of " + p.Items.Type
			}
			req := "no"
			if required[n] {
				req = "**yes**"
			}
			fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", n, typ, req, cell(p.Description))
		}
	}
}

// cell makes a string safe inside a markdown table: a pipe would end the column
// and a newline would end the row.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	return strings.Join(strings.Fields(s), " ")
}

func or(s, fallback string) string {
	if strings.TrimSpace(s) == "" {
		return fallback
	}
	return s
}
