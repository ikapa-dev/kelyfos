func cliPage(cmds []Command) string {
	var b strings.Builder
	b.WriteString(banner)
	b.WriteString("\n# CLI reference\n\nEvery command and every flag, from each command's own flag set.\n" +
		"Go's `flag` accepts one dash or two, so `-image` and `--image` are the same flag.\n\n")

	b.WriteString("| Command | What it does |\n| --- | --- |\n")
	for _, c := range cmds {
		b.WriteString(fmt.Sprintf("| [`kelyfos %s`](#kelyfos-%s) | %s |\n",
			c.Name, strings.ReplaceAll(c.Name, " ", "-"), or(c.Doc, "—")))
	}

	for _, c := range cmds {
		fmt.Fprintf(&b, "\n## kelyfos %s\n\n", c.Name)
		if c.Doc != "" {
			fmt.Fprintf(&b, "%s.\n\n", strings.ToUpper(c.Doc[:1])+c.Doc[1:])
		}
		fmt.Fprintf(&b, "```\n%s\n```\n\n", strings.TrimSpace("kelyfos "+c.Name+" "+c.Usage))
		if len(c.Flags) == 0 {
			b.WriteString("No flags.\n")
			continue
		}
		b.WriteString("| Flag | Type | Default | Meaning |\n| --- | --- | --- | --- |\n")
		for _, f := range c.Flags {
			// A one-letter flag is written with one dash, because that is how
			// anybody writes it and how the CLI's own help prints it. Go's flag
			// package accepts either for both, so this is about the reader.
			dashes := "--"
			if len(f.Name) == 1 {
				dashes = "-"
			}
			fmt.Fprintf(&b, "| `%s%s` | %s | %s | %s |\n",
				dashes, f.Name, or(f.Type, "—"), or(f.Default, "—"), or(cell(f.Doc), "—"))
		}
	}
	return b.String()
}

func configPage() string {
	var b strings.Builder
	b.WriteString(banner)
	b.WriteString("\n# `kelyfos.toml` reference\n\n" +
		"Every key the parser understands, and every key it refuses on purpose.\n" +
		"Anything not listed here is an error naming the line — the file never\n" +
		"skips a key it does not recognise.\n")

	for _, s := range Sections() {
		fmt.Fprintf(&b, "\n## `%s`\n\n%s.\n\n", s.Header, strings.ToUpper(s.Doc[:1])+s.Doc[1:])
		keys := config.KeysIn(s.Name)
		if len(keys) == 0 {
			b.WriteString("No keys.\n")
			continue
		}
		b.WriteString("| Key | Type | Default | Meaning |\n| --- | --- | --- | --- |\n")
		for _, k := range keys {
			meaning := cell(k.Doc)
			switch {
			case k.Refused != "":
				meaning = "**refused** — " + cell(k.Refused)
			case k.RefusedLater != "":
				meaning = cell(k.Doc) + " · **" + cell(k.RefusedLater) + "**"
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n",
				k.Name, k.Type, or(cell(k.Default), "—"), meaning)
		}
	}
	return b.String()
}

// Sections is config.Sections, reachable here so the page and the parser cannot
// disagree about which headers exist.
func Sections() []config.Section { return config.Sections() }

func eventsPage() string {
	var b strings.Builder
	b.WriteString(banner)
	b.WriteString("\n# Flight-recorder events\n\n" +
		"Every event type the host writes, with its payload. The concepts — why the\n" +
		"host writes all of it, what the hash chain does and does not prove — are in\n" +
		"[`../events.md`](../events.md).\n\n## Common fields\n\n" +
		"On every event, in the order the hash is computed over.\n\n")
	writeFields(&b, recorder.CommonFields())

	for _, e := range recorder.Types() {
		fmt.Fprintf(&b, "\n## `%s`\n\n%s. Written by the **%s**.\n\n",
			e.Type, strings.ToUpper(e.Doc[:1])+e.Doc[1:], e.Source)
		writeFields(&b, e.Fields)
	}
	return b.String()
}

func writeFields(b *strings.Builder, fields []recorder.Field) {
	b.WriteString("| Field | Type | Meaning |\n| --- | --- | --- |\n")
	for _, f := range fields {
		doc := cell(f.Doc)
		if f.When != "" {
			doc += " *(" + cell(f.When) + ")*"
		}
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", f.Name, f.Type, doc)
	}
}

// denialsPage is the refusal catalog (E5-4). Every entry is printed as it is
// actually raised — message, ID and fix line, rendered with the entry's own
// sample values — so this page is a page of real refusals rather than a page of
// templates. What a reader matches against what their terminal showed them is
// the same string, built by the same code.
func denialsPage() string {
	var b strings.Builder
	b.WriteString(banner)
	b.WriteString("\n# Denials\n\n" +
		"Every refusal that carries an ID, with the fix. A refusal prints its ID in\n" +
		"brackets; that ID is the heading to look for here.\n\n" +
		"Refusals raised while reading `kelyfos.toml` or validating a team plan are not\n" +
		"here: they name their own file and line instead of an ID, because the thing to\n" +
		"go and look at is the line you wrote.\n\n" +
		"Failures are not here. \"The upstream did not answer\" is not a refusal, has no\n" +
		"fix line, and nothing you type changes it.\n")
	for _, d := range denial.All() {
		fmt.Fprintf(&b, "\n## `%s`\n\n%s.\n\n```\n%s\n```\n",
			d.ID, sentence(d.Doc), d.Render(d.Sample))
		if p := d.Placeholders(); len(p) > 0 {
			fmt.Fprintf(&b, "\nNamed: %s. The values above are an example.\n", code(p))
		}
	}
	return b.String()
}

// sentence makes a catalog Doc — written lowercase, like every other table in
// this repository — stand on its own under a heading.
func sentence(s string) string {
	s = strings.TrimSuffix(s, ".")
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func code(names []string) string {
	out := make([]string, len(names))
	for i, n := range names {
		out[i] = "`" + n + "`"
	}
	return strings.Join(out, ", ")
}

// checkDenialsRaised fails the build when a catalog entry is raised nowhere.
//
// The catalog is only worth having if it is the refusals the product actually
// makes. An entry nothing raises is a promise in the documentation with no code
// behind it, which is exactly the failure the generated reference exists to
// prevent (F-D4) — so it is checked in the same place, by reading which
// `denial.X` identifiers the non-test source mentions.
func checkDenialsRaised(repo string) error {
	names, err := denialNames(filepath.Join(repo, "internal", "denial", "denial.go"))
	if err != nil {
		return err
	}
	raised := map[string]bool{}
	fset := token.NewFileSet()
	for _, dir := range []string{"host", "internal", "supervisor"} {
		err := filepath.WalkDir(filepath.Join(repo, dir), func(path string, e os.DirEntry, err error) error {
			if err != nil || e.IsDir() || !strings.HasSuffix(path, ".go") ||
				strings.HasSuffix(path, "_test.go") ||
				strings.Contains(path, filepath.Join("internal", "denial")) {
				return err
			}
			f, err := parser.ParseFile(fset, path, nil, 0)
			if err != nil {
				return err
			}
			ast.Inspect(f, func(n ast.Node) bool {
				sel, ok := n.(*ast.SelectorExpr)
				if !ok {
					return true
				}
				if id, ok := sel.X.(*ast.Ident); ok && id.Name == "denial" {
					raised[sel.Sel.Name] = true
				}
				return true
			})
			return nil
		})
		if err != nil {
			return err
		}
	}
	var unraised []string
	for name, id := range names {
		if !raised[name] {
			unraised = append(unraised, id)
		}
	}
	if len(unraised) > 0 {
		sort.Strings(unraised)
		return fmt.Errorf("the denial catalog lists %s, and nothing raises %s.\n"+
			"A refusal documented but never made is a promise with no code behind it: "+
			"raise it where it belongs, or delete the entry from internal/denial",
			strings.Join(quoteAll(unraised), ", "), plural(len(unraised), "it", "them"))
	}
	return nil
}

// denialNames reads the catalog's own source for the Go identifier of each
// entry and the ID it carries, so the check can report the ID a person reads
// rather than the variable a programmer typed.
func denialNames(path string) (map[string]string, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, 0)
	if err != nil {
		return nil, err
	}
	names := map[string]string{}
	ast.Inspect(file, func(n ast.Node) bool {
		vs, ok := n.(*ast.ValueSpec)
		if !ok || len(vs.Names) != 1 || len(vs.Values) != 1 {
			return true
		}
		lit, ok := vs.Values[0].(*ast.CompositeLit)
		if !ok {
			return true
		}
		if id, ok := lit.Type.(*ast.Ident); !ok || id.Name != "Denial" {
			return true
		}
		for _, el := range lit.Elts {
			kv, ok := el.(*ast.KeyValueExpr)
			if !ok {
				continue
			}
			if k, ok := kv.Key.(*ast.Ident); !ok || k.Name != "ID" {
				continue
			}
			if s, ok := kv.Value.(*ast.BasicLit); ok && s.Kind == token.STRING {
				if v, err := strconv.Unquote(s.Value); err == nil {
					names[vs.Names[0].Name] = v
				}
			}
		}
		return true
	})
	if len(names) == 0 {
		return nil, fmt.Errorf("no denial entries found in %s", path)
	}
	return names, nil
}

